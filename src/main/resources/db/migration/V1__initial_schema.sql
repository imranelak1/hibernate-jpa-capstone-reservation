-- Schéma initial H2 1.4; le champ description est introduit par V2.
CREATE TABLE IF NOT EXISTS utilisateurs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL, nom VARCHAR(255) NOT NULL,
 version INTEGER DEFAULT 0 NOT NULL
);
CREATE TABLE IF NOT EXISTS salles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom VARCHAR(255) NOT NULL UNIQUE, capacite INTEGER NOT NULL CHECK (capacite > 0),
 version INTEGER DEFAULT 0 NOT NULL
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 salle_id BIGINT NOT NULL REFERENCES salles(id),
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
 date_debut TIMESTAMP NOT NULL, date_fin TIMESTAMP NOT NULL,
 version INTEGER DEFAULT 0 NOT NULL,
 CHECK (date_fin > date_debut)
);
CREATE INDEX IF NOT EXISTS idx_reservation_salle_dates ON reservations(salle_id, date_debut, date_fin);
